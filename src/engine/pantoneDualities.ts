/**
 * Convert Hex to CMYK color array [0-100, 0-100, 0-100, 0-100]
 */
export function hexToCmyk(hex: string): [number, number, number, number] {
  let cleanHex = hex.replace('#', '');
  if (cleanHex.length === 3) {
    cleanHex = cleanHex.split('').map(c => c + c).join('');
  }
  const r = parseInt(cleanHex.substring(0, 2), 16) / 255;
  const g = parseInt(cleanHex.substring(2, 4), 16) / 255;
  const b = parseInt(cleanHex.substring(4, 6), 16) / 255;

  const k = 1 - Math.max(r, g, b);
  if (k === 1) return [0, 0, 0, 100];

  const c = (1 - r - k) / (1 - k);
  const m = (1 - g - k) / (1 - k);
  const y = (1 - b - k) / (1 - k);

  return [
    Math.round(c * 100),
    Math.round(m * 100),
    Math.round(y * 100),
    Math.round(k * 100),
  ];
}

/**
 * Find closest matching Pantone spot color
 */
export function findClosestPantone(hex: string): PantoneColor {
  const [c, m, y, k] = hexToCmyk(hex);
  let best = PANTONE_DUALITIES_2025[0];
  let minDiff = Infinity;

  for (const p of PANTONE_DUALITIES_2025) {
    const [pc, pm, py, pk] = p.cmyk;
    const diff = Math.sqrt(
      Math.pow(c - pc, 2) +
      Math.pow(m - pm, 2) +
      Math.pow(y - py, 2) +
      Math.pow(k - pk, 2)
    );
    if (diff < minDiff) {
      minDiff = diff;
      best = p;
    }
  }
  return best;
}
